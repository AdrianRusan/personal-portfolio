import type { Metadata } from "next";
import { Geist_Mono, Host_Grotesk } from "next/font/google";
import "./globals.css";
import { ThemeProvider } from "@/context/theme-provider";
import { Analytics } from "@vercel/analytics/react";
import { SpeedInsights } from "@vercel/speed-insights/next";
import { organizationJsonLd, personJsonLd } from "@/lib/person-schema";
import { JsonLd } from "@/lib/page-schema";
import { HOME_DESCRIPTION, HOME_SHARE_TITLE, SITE_TAGLINE, SITE_TITLE } from "@/data";

// #114 M: one variable grotesk for text and display, a mono for small meta.
// `subsets` only picks what is preloaded: the latin-ext faces (ă, ș, ț) are
// still in the CSS and load on demand on /ro. The mono is preloaded too: the
// hero eyebrow uses it above the fold, and a late swap would shift the H1.
const sans = Host_Grotesk({
  subsets: ["latin"],
  display: "swap",
  variable: "--font-sans",
});
const mono = Geist_Mono({
  subsets: ["latin"],
  weight: "400",
  display: "swap",
  variable: "--font-mono",
});

// ≤155 characters so Google shows it whole (A1-17). #125: one description,
// the homepage's, for the default meta tag and the layout's share card.
const DESCRIPTION = HOME_DESCRIPTION;

